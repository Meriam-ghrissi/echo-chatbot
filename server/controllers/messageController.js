import imagekit from "../configs/imageKit.js"
import Chat from "../models/Chat.js"
import User from "../models/User.js"
import openai from "../configs/openai.js"
import axios from "axios"


// Fetch generated image, retrying while ImageKit prepares it
const fetchGeneratedImage = async (url, maxRetries = 10, delayMs = 3000) => {
    for (let i = 0; i < maxRetries; i++) {
        const response = await axios.get(url, { responseType: "arraybuffer" });
        const contentType = response.headers['content-type'] || '';

        if (contentType.startsWith('image/')) {
            return response;
        }

        await new Promise(resolve => setTimeout(resolve, delayMs));
    }
    throw new Error("Image generation timed out");
};

// Text-based AI Chat Message Controller
export const textMessageController = async (req, res) => {
    try {
        const userId = req.user._id

        // Check credits
        if(req.user.credits < 1){
            return res.json({success: false, message: "You don't have enough credits to use this feature"})
        }

        const {chatId, prompt} = req.body

        const chat = await Chat.findOne({userId, _id: chatId})
        chat.messages.push({role: "user", content: prompt, timestamp: Date.now(), isImage: false})

        
        const { choices } = await openai.chat.completions.create({
            model: "gemini-3.5-flash",
            messages: [
                {
                    role: "user",
                    content: prompt,
                },
            ],
        });

        const reply = {...choices[0].message, timestamp: Date.now(), isImage: false}
        res.json({success: true, reply})
        chat.messages.push(reply)
        await chat.save()
        await User.updateOne({_id: userId}, {$inc: {credits: -1}})


    } catch (error) {
        res.json({success: false, message: error.message})
    }
}


// Image Generation Message Controller
export const imageMessageController = async (req, res) => {
    try {
        const userId = req.user._id;
        // Check credits
        if(req.user.credits < 2){
            return res.json({success: false, message: "You don't have enough credits to use this feature"})
        }
        const {prompt, chatId, isPublished} = req.body
        // Find chat
        const chat = await Chat.findOne({userId, _id: chatId})

        // Push user message
        chat.messages.push({
            role: "user",
            content: prompt,
            timestamp: Date.now(),
            isImage: false});

        // Encode the prompt
        const encodedPrompt = encodeURIComponent(prompt)

        // Construct ImageKit AI generation URL
        const generatedImageUrl = `${process.env.IMAGEKIT_URL_ENDPOINT}/ik-genimg-prompt-${encodedPrompt}/echo/${Date.now()}.png?tr=w-800,h-800`;

        // Trigger generated by fetching from ImageKit
        const aiImageResponse = await fetchGeneratedImage(generatedImageUrl)

        // Convert to Base 64
        const base64Image = `data:image/png;base64,${Buffer.from(aiImageResponse.data,"binary").toString('base64')}`

        // Upload to ImageKit Media Library
        const UploadResponse = await imagekit.upload({
            file: base64Image,
            fileName: `${Date.now()}.png`,
            folder: "echo"
        })

        const reply = {
            role: 'assistant', 
            content: UploadResponse.url,
            timestamp: Date.now(), 
            isImage: true,
            isPublished
        }

        res.json({success: true, reply})

        chat.messages.push(reply)
        await chat.save()
        await User.updateOne({_id: userId}, {$inc: {credits: -1}})



    } catch (error) {
        res.json({ success: false, message: error.message});
    }
}